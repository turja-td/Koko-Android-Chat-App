import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';
import 'package:provider/provider.dart';

import 'config.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'screens/auth_screen.dart';
import 'screens/home_screen.dart';
import 'services/chat_watcher.dart';
import 'theme/app_theme.dart';
import 'theme/theme_controller.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  await ChatWatcher.instance.init();
  final themeController = await ThemeController.load();
  runApp(ChangeNotifierProvider.value(value: themeController, child: const KokoApp()));
}

class KokoApp extends StatelessWidget {
  const KokoApp({super.key});

  @override
  Widget build(BuildContext context) {
    final tc = context.watch<ThemeController>();
    return MaterialApp(
      title: AppInfo.name,
      debugShowCheckedModeBanner: false,
      navigatorKey: ChatWatcher.navigatorKey,
      theme: AppTheme.build(Brightness.light, tc.seed, tc.font),
      darkTheme: AppTheme.build(Brightness.dark, tc.seed, tc.font),
      themeMode: tc.mode,
      themeAnimationDuration: const Duration(milliseconds: 400),
      themeAnimationCurve: Curves.easeInOut,
      builder: (context, child) {
        // Our own text-size setting on top of the system one.
        final system = MediaQuery.textScalerOf(context).scale(1.0);
        return MediaQuery(
          data: MediaQuery.of(context).copyWith(textScaler: TextScaler.linear(system * tc.textScale)),
          child: child!,
        );
      },
      home: StreamBuilder<User?>(
        stream: FirebaseAuth.instance.authStateChanges(),
        builder: (context, snap) {
          if (snap.connectionState == ConnectionState.waiting) {
            return const Scaffold(body: Center(child: CircularProgressIndicator()));
          }
          return AnimatedSwitcher(
            duration: const Duration(milliseconds: 450),
            switchInCurve: Curves.easeOut,
            switchOutCurve: Curves.easeIn,
            child: snap.hasData
                ? const HomeScreen(key: ValueKey('home'))
                : const AuthScreen(key: ValueKey('auth')),
          );
        },
      ),
    );
  }
}
